import { createFileRoute } from "@tanstack/react-router";
import { useState } from "react";
import { Bar, BarChart, CartesianGrid, Cell, Pie, PieChart, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import { Download, Plus } from "lucide-react";
import { toast } from "sonner";
import { useScope } from "@/lib/workspace";
import { monthlyIncome, propertyStats } from "@/lib/ledger";
import { eur } from "@/lib/proration";
import { downloadReceipt } from "@/lib/receipt";
import { meta } from "@/lib/seo";
import { Metric, PageHeader, Panel } from "@/components/hk/kit";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Dialog, DialogContent, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog";

export const Route = createFileRoute("/owners/reports")({
  head: () => meta("Reports", "Income, expenses and net yield for your property."),
  component: Reports,
});

const colors = ["var(--color-chart-1)", "var(--color-chart-2)", "var(--color-chart-3)", "var(--color-chart-4)", "var(--color-chart-5)"];

function Reports() {
  const { property, pick, data, actions } = useScope();
  const income = monthlyIncome({ ...data, payments: pick(data.payments) }, 6);
  const collected = income.reduce((s, m) => s + m.collected, 0);
  const expenses = pick(data.expenses);
  const maint = pick(data.maintenance).reduce((s, m) => s + (m.cost ?? 0), 0);
  const spent = expenses.reduce((s, e) => s + e.amount, 0);
  const byCat = Object.entries(expenses.reduce<Record<string, number>>((a, e) => ({ ...a, [e.category]: (a[e.category] ?? 0) + e.amount }), {})).map(([name, value]) => ({ name, value }));
  const s = propertyStats(data, property!.id);
  const [open, setOpen] = useState(false);
  const [f, setF] = useState({ category: "Maintenance", description: "", amount: "", date: new Date().toISOString().slice(0, 10) });

  const add = async () => {
    if (!f.description.trim() || !(Number(f.amount) > 0)) return toast.error("Description and amount required.");
    await actions.addExpense({ propertyId: property!.id, category: f.category, description: f.description, amount: Number(f.amount), date: f.date });
    setOpen(false);
    toast.success("Expense recorded");
  };

  const exportPdf = () => downloadReceipt({ title: `${property!.name} · 6-month report`, ref: `RPT-${new Date().toISOString().slice(0, 10)}`, date: new Date().toISOString(), lines: [...income.map((m) => [`Rent collected · ${m.m}`, eur(m.collected)] as [string, string]), ["Property expenses", eur(-spent)], ["Occupancy now", `${s.occupancyRate}%`]], total: { label: "Net (6 months)", amount: collected - spent }, note: "Generated by HouseKey for Owners from the recorded ledger." });

  return (
    <>
      <PageHeader eyebrow={property!.name} title="Reports" actions={<><Button variant="outline" onClick={() => setOpen(true)}><Plus className="h-4 w-4" /> Record expense</Button><Button onClick={exportPdf}><Download className="h-4 w-4" /> Export PDF</Button></>} />
      <div className="grid grid-cols-2 gap-px overflow-hidden rounded-lg border bg-border md:grid-cols-4">
        <Metric label="Rent collected · 6 mo" value={eur(collected)} />
        <Metric label="Expenses recorded" value={eur(spent)} />
        <Metric label="Maintenance costs" value={eur(maint)} />
        <Metric label="Net" value={eur(collected - spent)} accent />
      </div>
      <div className="mt-6 grid gap-6 lg:grid-cols-[1.4fr_1fr]">
        <Panel title="Collection history">
          <div className="h-64"><ResponsiveContainer width="100%" height="100%"><BarChart data={income}><CartesianGrid vertical={false} stroke="var(--color-border)" /><XAxis dataKey="m" tickLine={false} axisLine={false} fontSize={12} /><YAxis tickLine={false} axisLine={false} fontSize={12} width={52} /><Tooltip formatter={(v: number) => eur(v)} /><Bar dataKey="collected" name="Collected" stackId="a" fill="var(--color-chart-1)" /><Bar dataKey="pending" name="Pending" stackId="a" fill="var(--color-chart-2)" radius={[3, 3, 0, 0]} /></BarChart></ResponsiveContainer></div>
        </Panel>
        <Panel title="Expenses by category">
          {byCat.length === 0 ? <p className="text-sm text-muted-foreground">No expenses yet.</p> : (
            <>
              <div className="h-44"><ResponsiveContainer width="100%" height="100%"><PieChart><Pie data={byCat} dataKey="value" nameKey="name" innerRadius={45} outerRadius={70} paddingAngle={2}>{byCat.map((_, i) => <Cell key={i} fill={colors[i % colors.length]} />)}</Pie><Tooltip formatter={(v: number) => eur(v)} /></PieChart></ResponsiveContainer></div>
              <div className="mt-2 space-y-1">{byCat.map((c, i) => <div key={c.name} className="flex items-center justify-between text-sm"><span className="flex items-center gap-2"><span className="h-2 w-2 rounded-full" style={{ background: colors[i % colors.length] }} />{c.name}</span><span className="num">{eur(c.value)}</span></div>)}</div>
            </>
          )}
        </Panel>
      </div>
      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent>
          <DialogHeader><DialogTitle className="font-display font-normal">Record a property expense</DialogTitle></DialogHeader>
          <div className="space-y-3">
            <div><Label>Category</Label><Select value={f.category} onValueChange={(v) => setF({ ...f, category: v })}><SelectTrigger><SelectValue /></SelectTrigger><SelectContent>{["Maintenance", "Insurance", "Fees", "Furnishing", "Tax", "Other"].map((c) => <SelectItem key={c} value={c}>{c}</SelectItem>)}</SelectContent></Select></div>
            <div><Label>Description</Label><Input value={f.description} onChange={(e) => setF({ ...f, description: e.target.value })} /></div>
            <div className="grid grid-cols-2 gap-3"><div><Label>Amount (€)</Label><Input type="number" value={f.amount} onChange={(e) => setF({ ...f, amount: e.target.value })} /></div><div><Label>Date</Label><Input type="date" value={f.date} onChange={(e) => setF({ ...f, date: e.target.value })} /></div></div>
          </div>
          <DialogFooter><Button onClick={add}>Save expense</Button></DialogFooter>
        </DialogContent>
      </Dialog>
    </>
  );
}
